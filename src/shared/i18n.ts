export type MsgKey = keyof typeof ko;

function detect(): 'ko' | 'en' {
  try {
    const l = (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage?.()) || navigator.language || 'ko';
    return l.toLowerCase().startsWith('ko') ? 'ko' : 'en';
  } catch {
    return 'ko';
  }
}

export const LANG = detect();
const dict = LANG === 'ko' ? ko : en;

export function t(key: MsgKey, ...args: Array<string | number>): string {
  return dict[key].replace(/\{(\d)\}/g, (_m, i: string) => String(args[Number(i)] ?? ''));
}
